  /* чистая логика: picks — массив ответов игроков; mode: 'together' (очко, если совпали все) | 'compete' (очко за совпадение с наибольшей группой) */
  const tpNorm = s => String(s == null ? '' : s).toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
  const tpMult = k => k >= 5 ? 3 : k >= 3 ? 2 : 1;
  function tpRound(picks, mode) {
    const n = picks.length, g = new Map();
    picks.forEach((p, i) => { const k = tpNorm(p); if (!g.has(k)) g.set(k, []); g.get(k).push(i); });
    const top = Math.max(...[...g.values()].map(a => a.length));
    const full = top === n;
    const hit = picks.map(p => mode === 'together' ? full : (top >= 2 && g.get(tpNorm(p)).length === top));
    return { top, full, hit, agree: n > 1 ? (top - 1) / (n - 1) : 0 };
  }
